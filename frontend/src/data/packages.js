export const allPackages = [...packages3Star, ...packages4Star, ...packages5Star];

export function getPackageBySlug(slug) {
  return allPackages.find((pkg) => pkg.slug === slug);
}

export function getRelevantPackages(pkg, limit = 2) {
  return allPackages
    .filter((item) => item.id !== pkg.id && item.nightsTotal === pkg.nightsTotal)
    .slice(0, limit);
}

export function getStarString(starCount) {
  return "★".repeat(starCount || 5);
}
